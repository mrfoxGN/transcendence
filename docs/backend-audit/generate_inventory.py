"""Regenerate static route, DTO and schema references; no imports or service startup."""
from pathlib import Path
import json,re,subprocess
ROOT=Path(__file__).resolve().parents[2]
OUT=Path(__file__).resolve().parent
SRC=ROOT/'apps/backend/src'
REV=subprocess.check_output(['git','rev-parse','HEAD:apps/backend/src'],cwd=ROOT,text=True).strip()
def link(p,line=1):
 rel=p.relative_to(ROOT).as_posix()
 return f'[{rel}:{line}](../../{rel}#L{line})'
def balanced(text,start,opening='(',closing=')'):
 depth=0;quote=None;escape=False
 for i in range(start,len(text)):
  c=text[i]
  if quote:
   if escape:escape=False
   elif c=='\\':escape=True
   elif c==quote:quote=None
  elif c in "\"'`":quote=c
  elif c==opening:depth+=1
  elif c==closing:
   depth-=1
   if not depth:return i
 raise ValueError('Unbalanced signature')
routes=[]
controllers=sorted(SRC.rglob('*.controller.ts'))
for p in controllers:
 text=p.read_text();base=re.search(r"@Controller\(\s*(?:['\"]([^'\"]*)['\"])?\s*\)",text)
 if not base:raise ValueError(str(p))
 prefix=base.group(1) or ''
 classguard='JwtAuthGuard' in text[base.start():text.index('export class')]
 hits=list(re.finditer(r"@(Get|Post|Put|Patch|Delete|Head|Options)\(\s*(?:['\"]([^'\"]*)['\"])?\s*\)",text))
 for j,hit in enumerate(hits):
  stop=hits[j+1].start() if j+1<len(hits) else len(text)
  section=text[hit.end():stop]
  method=re.search(r'^  (?:async )?([a-zA-Z_]\w*)\s*\(',section,re.M)
  if not method:raise ValueError(str(p)+': no handler')
  start=hit.end()+method.start();paren=text.index('(',start);end=balanced(text,paren)
  cursor=end+1;angles=0;squares=0;braces=0
  while cursor<len(text):
   c=text[cursor]
   if c=='{':
    if angles==0 and squares==0 and braces==0:break
    braces+=1
   elif c=='}':braces-=1
   elif c=='<':angles+=1
   elif c=='>':angles-=1
   elif c=='[':squares+=1
   elif c==']':squares-=1
   cursor+=1
  signature=text[start:cursor].strip()
  decorators=text[hit.end():start]
  code=re.search(r'@HttpCode\((\d+)\)',decorators)
  status=int(code.group(1)) if code else (201 if hit.group(1)=='Post' else 200)
  path='/'+('/'.join([prefix,hit.group(2) or '']).strip('/'))
  routes.append(dict(method=hit.group(1).upper(),path=path,handler=method.group(1),status=status,auth='Bearer JWT' if classguard or 'JwtAuthGuard' in decorators else 'Public / callback',source=p.relative_to(ROOT).as_posix(),line=text.count('\n',0,hit.start())+1,signature=signature))
keys=[(r['method'],r['path']) for r in routes]
assert len(keys)==len(set(keys)),'Duplicate route'
(OUT/'inventory.json').write_text(json.dumps({'backendSourceTree':REV,'basis':'static source inspection; no runtime claims','routes':routes},indent=2)+'\n')
lines=['# HTTP API catalog','',f'Backend source tree: `{REV}`. {len(routes)} controller operations. Generated by `python3 docs/backend-audit/generate_inventory.py`.','',
'Paths below are native Nest paths. Browser clients normally prepend `/api` through the existing Nginx proxy, which removes that prefix. `status` is the declared/default success code, not a guarantee for every branch; 204/no-content and OAuth redirect exceptions are discussed in the feature guide.','',
'Payloads and query contracts are linked in [DTO reference](DTO_REFERENCE.md). For handlers with inferred return types, follow the source link to the service implementation. Swagger is separate middleware, not a controller entry.','']
for p in controllers:
 items=[r for r in routes if r['source']==p.relative_to(ROOT).as_posix()]
 if not items:continue
 lines+=['## '+p.stem.replace('.controller',''),'','| Method | Native path | Authentication | Success | Handler |','|---|---|---|---|---|']
 for r in items:lines.append(f"| {r['method']} | `{r['path']}` | {r['auth']} | {r['status']} | `{r['handler']}` |")
 for r in items:lines+=['',f"### {r['method']} `{r['path']}`",'',link(p,r['line']),'','```ts',r['signature'],'```']
 lines.append('')
(OUT/'HTTP_API.md').write_text('\n'.join(line.rstrip() for line in '\n'.join(lines).splitlines()).rstrip()+'\n')
dtos=sorted(SRC.glob('modules/*/dto/*.ts'))
lines=['# DTO and validation reference','',f'Exact source snapshots for {len(dtos)} DTO files at backend source tree `{REV}`. Regenerate after backend changes. Optionality, nullability, enum values, length limits and transforms below are authoritative source declarations; service-level checks still apply.','',
'Class-level validation uses whitelist + forbidNonWhitelisted + transform. Do not infer accepted request fields from response DTOs. Inline controller contracts follow the DTO files.','']
for p in dtos:lines+=['## '+str(p.relative_to(SRC)),'',link(p),'','```ts',p.read_text().strip(),'```','']
for p in controllers:
 text=p.read_text()
 for match in re.finditer(r'^class (\w+)\s*\{',text,re.M):
  start=text.index('{',match.start());end=balanced(text,start,'{','}')
  lines+=['## Inline '+match.group(1),'',link(p,text.count('\n',0,match.start())+1),'','```ts',text[match.start():end+1],'```','']
(OUT/'DTO_REFERENCE.md').write_text('\n'.join(line.rstrip() for line in '\n'.join(lines).splitlines()).rstrip()+'\n')
lines=['# Schema and configuration inventory','',f'Static snapshot at backend source tree `{REV}`. Migration files are present; this audit did not execute them or assert a deployed database schema.','',
'## Enums','',link(SRC/'database/enums/database.enums.ts'),'','```ts',(SRC/'database/enums/database.enums.ts').read_text().strip(),'```','','## Migration files','']
for p in sorted((SRC/'database/migrations').glob('*.ts')):lines.append('- '+link(p))
lines+=['','Two migrations share the numeric timestamp `1795600000000`. This is a source observation, not a tested migration failure; verify migration ordering in an isolated environment before deployment.','','## Entity files','']
for p in sorted(SRC.rglob('*.entity.ts')):lines.append('- '+link(p))
variables=set()
for p in SRC.rglob('*.ts'):
 if '.spec.' in p.name:continue
 t=p.read_text();variables.update(re.findall(r'process\.env\.([A-Z][A-Z0-9_]+)',t));variables.update(re.findall(r"(?:get|getOrThrow)(?:<[^>]+>)?\(['\"]([A-Z][A-Z0-9_]+)['\"]",t))
lines+=['','## Environment variable names read by backend source','','Names only; no secrets or `.env` values were inspected or copied. Runtime requirements vary by feature.','',', '.join('`'+v+'`' for v in sorted(variables)),'','See [feature guide](FEATURES.md) for authentication/email/OAuth requirements and [migration notes](MIGRATION.md) before starting another Compose stack.']
(OUT/'SCHEMA_AND_CONFIG.md').write_text('\n'.join(line.rstrip() for line in '\n'.join(lines).splitlines()).rstrip()+'\n')
print(f'Generated {len(routes)} routes, {len(dtos)} DTO files, schema/config inventory.')
